#!/bin/sh
# BSDTV network ad blocking: turn public host blocklists into an unbound
# include for FreeBSD's local_unbound. Every device that uses the TV box as
# its DNS server benefits, and so does the TV itself.
#
# Usage: bsdtv-adblock-update [--dry-run]
#   Lists:     /usr/local/etc/bsdtv/adblock-lists.txt (one URL per line)
#   Allowlist: /usr/local/etc/bsdtv/adblock-allow.txt (one domain per line)

set -eu

ETC=${BSDTV_ETC:-/usr/local/etc/bsdtv}
OUT=${BSDTV_ADBLOCK_OUT:-/var/unbound/conf.d/bsdtv-adblock.conf}
LISTS=$ETC/adblock-lists.txt
ALLOW=$ETC/adblock-allow.txt
DEFAULT_LIST=https://raw.githubusercontent.com/StevenBlack/hosts/master/hosts

dry_run=no
[ "${1:-}" = "--dry-run" ] && dry_run=yes

work=$(mktemp -d "${TMPDIR:-/tmp}/bsdtv-adblock.XXXXXX")
trap 'rm -rf "$work"' EXIT INT TERM

download() {
	if command -v fetch >/dev/null 2>&1; then
		fetch -q -T 60 -o "$2" "$1"
	else
		curl -fsSL --max-time 60 -o "$2" "$1"
	fi
}

urls=$DEFAULT_LIST
if [ -r "$LISTS" ]; then
	urls=$(grep -Ev '^[[:space:]]*(#|$)' "$LISTS" || true)
fi

n=0
for url in $urls; do
	n=$((n + 1))
	if ! download "$url" "$work/list.$n"; then
		echo "bsdtv-adblock: could not download $url, skipping" >&2
		rm -f "$work/list.$n"
	fi
done

if ! ls "$work"/list.* >/dev/null 2>&1; then
	echo "bsdtv-adblock: no list downloaded, keeping the current block list" >&2
	exit 1
fi

# Accept "hosts" lines (0.0.0.0 domain) and plain domain lists.
cat "$work"/list.* |
	tr -d '\r' |
	sed -e 's/#.*//' |
	awk '{ d = (NF >= 2 && ($1 == "0.0.0.0" || $1 == "127.0.0.1")) ? $2 : (NF == 1 ? $1 : "") }
	     d != "" { print tolower(d) }' |
	grep -E '^[a-z0-9_-]+(\.[a-z0-9_-]+)+$' |
	grep -Ev '^(localhost|localhost\.localdomain|local|broadcasthost|0\.0\.0\.0)$' |
	sort -u > "$work/domains"

if [ -r "$ALLOW" ]; then
	grep -Ev '^[[:space:]]*(#|$)' "$ALLOW" | tr '[:upper:]' '[:lower:]' | sort -u > "$work/allow" || true
	comm -23 "$work/domains" "$work/allow" > "$work/domains.filtered"
	mv "$work/domains.filtered" "$work/domains"
fi

count=$(wc -l < "$work/domains" | tr -d ' ')
{
	echo "# Generated by bsdtv-adblock-update on $(date -u '+%Y-%m-%d %H:%M UTC'): $count domains"
	echo "server:"
	awk '{ printf "  local-zone: \"%s.\" always_nxdomain\n", $1 }' "$work/domains"
} > "$work/adblock.conf"

if [ "$dry_run" = yes ]; then
	head -n 5 "$work/adblock.conf"
	echo "... $count domains (dry run, nothing installed)"
	exit 0
fi

mkdir -p "$(dirname "$OUT")"
[ -f "$OUT" ] && cp "$OUT" "$OUT.prev"
install -m 0644 "$work/adblock.conf" "$OUT"

if command -v local-unbound-checkconf >/dev/null 2>&1 && ! local-unbound-checkconf >/dev/null 2>&1; then
	echo "bsdtv-adblock: unbound rejected the new list, restoring the previous one" >&2
	if [ -f "$OUT.prev" ]; then mv "$OUT.prev" "$OUT"; else rm -f "$OUT"; fi
	exit 1
fi
rm -f "$OUT.prev"

service local_unbound status >/dev/null 2>&1 && service local_unbound restart >/dev/null
echo "bsdtv-adblock: blocking $count domains"
